"""Cuts the supplied footstep recordings into single steps.

Reads sfx/footsteps/*.wav (user masters, not in git) and writes one short mono
WAV per step to assets/audio/sfx/footsteps/, plus game/audio/footstep_segments.gd
with the offset of each step's impact inside its clip, so the game can start a
clip early and land the impact exactly on the footfall.

Usage: python tools/audio/slice_footsteps.py
"""
import os
import wave

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "sfx", "footsteps")
TARGET = os.path.join(ROOT, "assets", "audio", "sfx", "footsteps")
TABLE = os.path.join(ROOT, "game", "audio", "footstep_segments.gd")

# name: (master, shortest gap between steps, pre-roll kept before the impact,
#        length after the impact, how late the loudest hit may follow the thump).
# Gaps come from each take's measured cadence: carpet walk 0.56 s, carpet run
# 0.34 s, hard floor 0.84 s (heel, then toe 0.21 s later, both kept in one step).
SETS = {
    "carpet_walk": ("footsteps-carpet.wav", 0.40, 0.10, 0.40, 0.12),
    "carpet_run": ("running-carpet.wav", 0.25, 0.08, 0.24, 0.05),
    "hard_walk": ("walk-hard-floor.wav", 0.50, 0.10, 0.50, 0.04),
}
MAX_STEPS = 12
PEAK_DB = -3.0


def load(path):
    with wave.open(path) as w:
        frames = w.readframes(w.getnframes())
        width = w.getsampwidth()
        channels = w.getnchannels()
        rate = w.getframerate()
    if width == 2:
        data = np.frombuffer(frames, np.int16).astype(np.float64) / 32768.0
    elif width == 4:
        data = np.frombuffer(frames, np.int32).astype(np.float64) / 2147483648.0
    else:
        raise ValueError(f"{path}: unsupported sample width {width}")
    return data.reshape(-1, channels).mean(axis=1), rate


def band(signal, rate, low, high):
    spectrum = np.fft.rfft(signal)
    freqs = np.fft.rfftfreq(len(signal), 1.0 / rate)
    spectrum[(freqs < low) | (freqs > high)] = 0
    return np.fft.irfft(spectrum, len(signal))


def envelope_db(signal, rate, hop_seconds):
    hop = int(rate * hop_seconds)
    count = len(signal) // hop
    frames = signal[: count * hop].reshape(count, hop)
    return 20 * np.log10(np.sqrt((frames ** 2).mean(axis=1)) + 1e-9)


def step_impacts(signal, rate, gap):
    """Impacts are the weight landing: the low-band thump of each step."""
    low = envelope_db(band(signal, rate, 40, 250), rate, 0.01)
    taken = []
    for index in np.argsort(-low):
        if low[index] < low.max() - 18:
            break
        if all(abs(index - other) * 0.01 >= gap for other in taken):
            taken.append(index)
    impacts = []
    broad = envelope_db(signal, rate, 0.005)
    for index in sorted(taken):
        peak_time = index * 0.01
        # Onset: first 5 ms frame within 12 dB of the local peak, up to 80 ms back.
        start = max(0, int((peak_time - 0.08) / 0.005))
        stop = min(len(broad), int((peak_time + 0.03) / 0.005))
        local = broad[start:stop]
        if len(local) == 0:
            continue
        onset = start + int(np.argmax(local > local.max() - 12))
        impacts.append(onset * 0.005)
    return impacts


def write_clip(path, clip, rate):
    pcm = np.clip(clip * 32767.0, -32768, 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(pcm.tobytes())


def main():
    os.makedirs(TARGET, exist_ok=True)
    for name in os.listdir(TARGET):
        if name.endswith(".wav") and name.split("_")[0] in ("carpet", "hard"):
            os.remove(os.path.join(TARGET, name))
    lines = [
        "## Generated by tools/audio/slice_footsteps.py; do not edit by hand.",
        "## One entry per step clip: path and the impact time inside the clip (s).",
        "const SETS := {",
    ]
    for name, (master, gap, preroll, tail, lag) in SETS.items():
        signal, rate = load(os.path.join(SOURCE, master))
        signal = band(signal, rate, 35, rate * 0.5)
        impacts = [t for t in step_impacts(signal, rate, gap) if t - preroll >= 0 and t + tail <= len(signal) / rate]
        clips = []
        for impact in impacts:
            clip = signal[int((impact - preroll) * rate): int((impact + tail) * rate)].copy()
            fade_in = int(0.01 * rate)
            fade_out = int(0.08 * rate)
            clip[:fade_in] *= np.linspace(0, 1, fade_in)
            clip[-fade_out:] *= np.linspace(1, 0, fade_out) ** 2
            # The audible hit inside the clip: onset of the loudest moment just
            # after the thump, which lags it a little on soft floors.
            env = envelope_db(clip, rate, 0.005)
            first = int((preroll - 0.02) / 0.005)
            peak = first + int(np.argmax(env[first: int((preroll + lag) / 0.005)]))
            onset = peak
            while onset > max(1, peak - 12) and env[onset - 1] > env[peak] - 6:
                onset -= 1
            crest = env[peak] - np.median(env)
            clips.append((clip, np.abs(clip).max(), impact, onset * 0.005, crest))
        # Keep the steps that stand out most from their own background, with the
        # whole set brought to a common peak.
        clips.sort(key=lambda item: -item[4])
        clips = clips[:MAX_STEPS]
        gain = 10 ** (PEAK_DB / 20) / np.median([item[1] for item in clips])
        lines.append(f'\t"{name}": [')
        for number, (clip, _, _, hit, _) in enumerate(sorted(clips, key=lambda item: item[2])):
            filename = f"{name}_{number + 1:02d}.wav"
            write_clip(os.path.join(TARGET, filename), np.clip(clip * gain, -0.98, 0.98), rate)
            lines.append(f'\t\t["res://assets/audio/sfx/footsteps/{filename}", {hit:.3f}],')
        lines.append("\t],")
        print(f"{name}: {len(impacts)} steps found, {len(clips)} kept, gain {20 * np.log10(gain):+.1f} dB")
    lines.append("}")
    for name in os.listdir(TARGET):
        if name.endswith(".wav.import") and not os.path.exists(os.path.join(TARGET, name[:-7])):
            os.remove(os.path.join(TARGET, name))
    with open(TABLE, "w", encoding="utf-8", newline="\n") as table:
        table.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
